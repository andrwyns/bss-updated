    //the static mesh primitives, wrapped so each prop can be written in its own space (ground at y=0, yaw and scale applied)
    function propSpace(box,cylinder,sphere,x0,y0,z0,yaw,s){

        let cs=Math.cos(yaw*DEG),sn=Math.sin(yaw*DEG)

        let P={}

        P.at=(lx,ly,lz)=>[x0+(lx*cs+lz*sn)*s,y0+ly*s,z0+(-lx*sn+lz*cs)*s]

        //a cylinder from local point a to local point b, radius ra at a and rb at b
        P.rod=(a,b,ra,col,rb=ra,sides=7)=>{

            let p=P.at(...a),q=P.at(...b),dx=q[0]-p[0],dy=q[1]-p[1],dz=q[2]-p[2],len=Math.hypot(dx,dy,dz)

            if(len<0.0001) return

            cylinder((p[0]+q[0])*0.5,(p[1]+q[1])*0.5,(p[2]+q[2])*0.5,rb*s,len,sides,col[0],col[1],col[2],1,Math.asin(-dy/len)/DEG||0.0001,Math.atan2(dx,dz)/DEG,0,ra*s)
        }

        //a ball: d is its diameter, ys squashes it vertically
        P.ball=(lx,ly,lz,d,col,ys=1,detail=1)=>{

            let p=P.at(lx,ly,lz)

            sphere(p[0],p[1],p[2],d*s,detail,col[0],col[1],col[2],1,ys)
        }

        P.block=(lx,ly,lz,w,h,l,col,ry=0)=>{

            let p=P.at(lx,ly,lz)

            box(p[0],p[1],p[2],w*s,h*s,l*s,[0,yaw+ry||0.0001,0],col,false,false)
        }

        return P
    }

